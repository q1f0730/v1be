import { test } from 'node:test'
import assert from 'node:assert/strict'
import { cacheStart, cacheStep, queueStart, queueStep, raceStart, raceStep, raceFinished, challengePassed } from './lab-engine.js'

test('LRU refreshes recency, evicts the oldest, and accounts for all latency', () => {
  let s = cacheStart(2)
  for (let i = 0; i < 5; i++) s = cacheStep(s)
  assert.deepEqual(s.keys, ['B', 'C'])
  assert.equal(s.last.evicted, 'A')
  while (s.cursor < 8) s = cacheStep(s)
  assert.equal(s.hits, 4)
  assert.equal(s.elapsed, 880)
  assert.equal(challengePassed('cache', s), true)
  assert.equal(cacheStep(s), s)
  let off = cacheStart(0)
  for (let i = 0; i < 8; i++) off = cacheStep(off)
  assert.equal(off.hits, 0)
  assert.equal(off.elapsed, 1600)
  assert.deepEqual(off.keys, [])
})
test('queue conserves tasks across overload, capacity, and burst traffic', () => {
  let s = queueStart(6, 1)
  for (let i = 0; i < 12; i++) {
    s = queueStep(s, i === 0 ? 10 : 0)
    assert.equal(s.nextId - 1, s.processed + s.tasks.length + s.rejected)
    assert.ok(s.tasks.length <= 30)
  }
  assert.ok(s.rejected > 0)
  assert.equal(queueStep(s), s)
  let balanced = queueStart(6, 3)
  for (let i = 0; i < 5; i++) balanced = queueStep(balanced)
  assert.equal(challengePassed('queue', balanced), true)
  assert.equal(balanced.processed, 30)
  let recovering = queueStart(6, 4)
  for (let i = 0; i < 5; i++) recovering = queueStep(recovering, i === 0 ? 10 : 0)
  assert.equal(recovering.tasks.length, 0)
  assert.equal(challengePassed('queue', recovering), false, 'one clear second is not five consecutive clear seconds')
  for (let i = 0; i < 4; i++) recovering = queueStep(recovering)
  assert.equal(challengePassed('queue', recovering), true)
})
test('interleaved unlocked increments lose an update; sequential execution does not', () => {
  let s = raceStart()
  for (let i = 0; i < 4; i++) s = raceStep(s)
  assert.equal(s.value, 1)
  assert.equal(raceFinished(s), true)
  assert.equal(raceStep(s), s)
  let sequential = raceStart()
  for (const who of ['A', 'A', 'B', 'B']) sequential = raceStep(sequential, who)
  assert.equal(sequential.value, 2)
})
test('lock spans read + write and blocks a second worker until release', () => {
  let s = raceStart(true)
  s = raceStep(s, 'A')
  s = raceStep(s, 'B')
  assert.equal(s.last.type, 'wait')
  assert.equal(s.actors.B.phase, 0)
  for (let i = 0; i < 5 && !raceFinished(s); i++) s = raceStep(s)
  assert.equal(s.value, 2)
  assert.equal(s.owner, null)
  assert.equal(challengePassed('race', s), true)
})
